<p>
	Use the settings panel to customize the planner to your liking. The preview updates
	live, and the page URL updates too — copy it to share your exact configuration with
	others.
</p>
<p>
	Pick a month and choose how many tasks you want to track. The planner builds a numbered
	index of those tasks — check each one off and note its due date, category, and a short
	description, then tap the link on the right to jump to that task's notes.
</p>
<p>
	Every task gets its own note page(s) for capturing details. Use the pills at the bottom
	of a task page to move between its pages. Set the number of tasks and note pages per
	task under "Tasks"; the index automatically spans extra pages when you track a lot of
	tasks.
</p>

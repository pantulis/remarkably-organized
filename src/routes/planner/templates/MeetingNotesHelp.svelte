<p>
	Use the settings panel to customize the planner to your liking. The preview updates
	live, and the page URL updates too — copy it to share your exact configuration with
	others.
</p>
<p>
	Pick a month and the planner generates one index page per week of that month. Each week
	lists your meetings — note the date, client, and a short description, then tap the link
	on the right to jump to that meeting's notes.
</p>
<p>
	Every meeting gets its own set of pages: a summary page (attendees, topics, and action
	points) followed by note pages. Use the pills at the bottom of a meeting page to move
	between its pages. Adjust how many meetings each week holds and how many note pages each
	meeting gets under "Meetings".
</p>
